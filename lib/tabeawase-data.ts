export function getAllSlugs(): string[] {
  return foodPairs.map((pair) => pair.slug);
}

export function getPairBySlug(slug: string): FoodPair | undefined {
  return foodPairs.find((pair) => pair.slug === slug);
}

export function getAllFoodNames(): string[] {
  const names = new Set<string>();
  for (const pair of foodPairs) {
    names.add(pair.foodA);
    names.add(pair.foodB);
  }
  return Array.from(names).sort((a, b) => a.localeCompare(b, "ja"));
}

export function findPairByFoods(foodA: string, foodB: string): FoodPair | undefined {
  return foodPairs.find(
    (pair) =>
      (pair.foodA === foodA && pair.foodB === foodB) ||
      (pair.foodA === foodB && pair.foodB === foodA)
  );
}

export function getRelatedPairs(pair: FoodPair, limit = 3): FoodPair[] {
  return foodPairs
    .filter(
      (p) =>
        p.slug !== pair.slug &&
        (p.relation === pair.relation ||
          p.foodA === pair.foodA ||
          p.foodA === pair.foodB ||
          p.foodB === pair.foodA ||
          p.foodB === pair.foodB)
    )
    .slice(0, limit);
}
